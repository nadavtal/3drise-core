/** True when the config is one of the vegetation variants (type 'vegetation', config.type set). */
export function isVegetationObjectConfig(config: unknown): config is VegetationObjectConfig {
    const t = (config as { type?: unknown } | null)?.type;
    return typeof t === 'string' && Object.prototype.hasOwnProperty.call(DEFAULT_VEGETATION_OBJECTS, t);
}
