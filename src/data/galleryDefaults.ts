/** Variants whose frames take the object's material (the rest draw with their own shaders). */
export const GALLERY_MATERIAL_VARIANTS: ReadonlySet<string> = new Set(['layout']);

/** True when the config is one of the gallery variants (type 'gallery', config.type set). */
export function isGalleryObjectConfig(config: unknown): config is GalleryObjectConfig {
    const t = (config as { type?: unknown } | null | undefined)?.type;
    return typeof t === 'string' && Object.prototype.hasOwnProperty.call(DEFAULT_GALLERY_OBJECTS, t);
}

/** True when this gallery's frames take a material (the layout gallery); false for variants with their own shaders. */
export function galleryTakesMaterial(config: unknown): boolean {
    const t = (config as { type?: unknown } | null | undefined)?.type;
    return typeof t !== 'string' || GALLERY_MATERIAL_VARIANTS.has(t);
}
