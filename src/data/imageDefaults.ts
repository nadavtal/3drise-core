/** True when the config is one of the image variants (type 'image', config.type set). */
export function isImageObjectConfig(config: unknown): config is ImageObjectConfig {
    const t = (config as { type?: unknown } | null | undefined)?.type;
    return typeof t === 'string' && Object.prototype.hasOwnProperty.call(DEFAULT_IMAGE_OBJECTS, t);
}
